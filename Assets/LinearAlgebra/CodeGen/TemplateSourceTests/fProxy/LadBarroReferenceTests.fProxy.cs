// Reference vectors from quantreg's own test suite (tests/rq.R) on the Barro growth data shipped
// with that package. quantreg asserts these coefficients at tol 1e-5 against R's rq(), which
// defaults to the Barrodale-Roberts method at this size. Reproducing them checks BOTH exact engines
// against a real-data, third-party result at tau = 0.25, 0.5 and 0.75 -- the only published
// non-median vectors in the tree (the brute-force oracle in LadFrischNewtonQuantileTests proves
// optimality; this proves agreement with the reference implementation).
//
// Two models, both with the intercept FIRST to match R's coef() ordering:
//   fit0 (tau 0.5):        y.net ~ lgdp2 + fse2 + gedy2
//   fit2/fit3 (0.75/0.25): y.net ~ lgdp2 + fse2 + gedy2 + Iy2 + gcony2
// Expected values are 100 * coef, exactly as quantreg writes them.
//
// Raw is 161 observations x 6 columns: y.net, lgdp2, fse2, gedy2, Iy2, gcony2. Regenerate with:
//   R:  load("barro.rda"); write.csv(barro, "barro.csv", row.names = FALSE)
//   sh: awk -F',' 'NR>1{printf "%s, %s, %s, %s, %s, %s,\n", $2,$3,$5,$10,$11,$12}' barro.csv
// The values are inlined rather than read at run time: the tests run headless in Burst with no
// working-directory guarantee, and the same template generates both the float and double variants.
public class fProxyLadBarroReferenceTests
{
    const int M = 161;
    const int Stride = 6;

    static readonly double[] Fit0Tau50 = { -0.74679759, 0.46539963, 0.15902838, -36.619915 };
    static readonly double[] Fit2Tau75 = { 13.103018, -1.4885239, -0.026452369, 0.3999839, 14.526663, -13.504643 };
    static readonly double[] Fit3Tau25 = { 6.0860719, -0.88350554, 0.24596781, -14.962498, 15.592489, -15.861804 };

    static void Build(int n, out fProxyMxN A, out fProxyN b)
    {
        A = new fProxyMxN(M, n, Allocator.Temp);
        b = new fProxyN(M, Allocator.Temp);
        for (int i = 0; i < M; i++)
        {
            int r = i * Stride;
            b[i] = (fProxy)Raw[r];
            A[i, 0] = (fProxy)1;
            A[i, 1] = (fProxy)Raw[r + 1];       // lgdp2
            A[i, 2] = (fProxy)Raw[r + 2];       // fse2
            A[i, 3] = (fProxy)Raw[r + 3];       // gedy2
            if (n == 6)
            {
                A[i, 4] = (fProxy)Raw[r + 4];   // Iy2
                A[i, 5] = (fProxy)Raw[r + 5];   // gcony2
            }
        }
    }

    // R's all.equal(target, current, tolerance) compares the MEAN relative difference
    // mean(|target - current|) / mean(|target|), not element-wise ratios -- which matters here
    // because the fse2 coefficient is ~500x smaller than the intercept.
    static double MeanRelativeDifference(double[] expect100, fProxyN got)
    {
        double num = 0, den = 0;
        for (int j = 0; j < expect100.Length; j++)
        {
            num += System.Math.Abs(expect100[j] - 100.0 * (double)got[j]);
            den += System.Math.Abs(expect100[j]);
        }
        return num / den;
    }

    static void Probe(System.Text.StringBuilder bad, string label, int n, double tau,
                      double[] expect100, double tolBR, double tolFN)
    {
        Build(n, out var A, out var b);
        var xBR = new fProxyN(n, Allocator.Temp);
        var xFN = new fProxyN(n, Allocator.Temp);

        LP.ladBR(in A, in b, tau, ref xBR, out double _);
        LP.ladFN(in A, in b, tau, ref xFN, out double _);

        double dBR = MeanRelativeDifference(expect100, xBR);
        double dFN = MeanRelativeDifference(expect100, xFN);
        if (dBR > tolBR) bad.AppendLine($"  {label} ladBR: mean relative difference {dBR:E3} > {tolBR:E1}");
        if (dFN > tolFN) bad.AppendLine($"  {label} ladFN: mean relative difference {dFN:E3} > {tolFN:E1}");

        A.Dispose(); b.Dispose(); xBR.Dispose(); xFN.Dispose();
    }

    // Each engine is held to what it can actually achieve, so neither hides behind the other.
    // Measured worst case over the three fits: double BR 9.8e-9 / FN 1.7e-8 -- both far inside
    // quantreg's own 1e-5 bar. Float BR 1.1e-6, float FN 2.6e-3: BR pivots on the ORIGINAL design
    // and stays near-exact, while FN solves the NORMAL equations and pays the squared condition
    // number. That 2000x split is the documented float limit in LP.FrischNewton's header, measured
    // here on real data rather than a synthetic case. lad's own routing sends m=161 to BR.
    [Test]
    public void MatchesQuantregPublishedCoefficients()
    {
        double tolBR = /*+choose[5e-6|1e-6]*/5e-6/*-choose*/;
        double tolFN = /*+choose[5e-3|1e-6]*/5e-3/*-choose*/;
        var bad = new System.Text.StringBuilder();
        Probe(bad, "fit0 tau=0.50", 4, 0.50, Fit0Tau50, tolBR, tolFN);
        Probe(bad, "fit2 tau=0.75", 6, 0.75, Fit2Tau75, tolBR, tolFN);
        Probe(bad, "fit3 tau=0.25", 6, 0.25, Fit3Tau25, tolBR, tolFN);
        Assert.That(bad.ToString(), Is.Empty, "quantreg reference coefficients not reproduced:\n" + bad);
    }

